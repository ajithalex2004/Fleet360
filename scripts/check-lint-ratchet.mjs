#!/usr/bin/env node
/**
 * scripts/check-lint-ratchet.mjs
 *
 * CI ratchet for `eslint .` — same idea as check-typecheck-ratchet.mjs,
 * applied to lint instead of tsc.
 *
 * As of 2026-09-17 the codebase has ~3,014 pre-existing ESLint errors
 * (mostly @typescript-eslint/no-unused-vars and @typescript-eslint/
 * no-explicit-any), which is why `npm run lint` runs as `continue-on-
 * error: true` in ci.yml rather than blocking outright. This script lets
 * CI block on lint again *without* requiring all ~3,014 to be fixed
 * first: it fails only if a file exceeds its baseline error count for a
 * given rule, or if a file with zero baseline errors introduces any.
 * Existing errors are grandfathered in; the total can only go down.
 *
 * USAGE
 * ─────
 *   node scripts/check-lint-ratchet.mjs
 *       Run the gate: fail if any file's per-rule error count increases
 *       versus scripts/lint-baseline.json, or any errors appear in a
 *       file with no baseline entry.
 *
 *   node scripts/check-lint-ratchet.mjs --update-baseline
 *       Regenerate scripts/lint-baseline.json from the current `eslint .`
 *       output. Run this after actually fixing errors (to lock in the
 *       lower count) — never run it to silence a real regression.
 */

import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { resolve, join, relative } from 'node:path';
import { exit, argv } from 'node:process';

const root = resolve(fileURLToPath(new URL('.', import.meta.url)), '..');
const BASELINE_PATH = join(root, 'scripts', 'lint-baseline.json');
const ESLINT_BIN = join(root, 'node_modules', '.bin', 'eslint');

function runEslintJson() {
  let stdout;
  try {
    stdout = execFileSync(ESLINT_BIN, ['.', '--format', 'json', '--max-warnings', '999999'], {
      cwd: root,
      encoding: 'utf8',
      maxBuffer: 1024 * 1024 * 200,
    });
  } catch (err) {
    // ESLint exits non-zero when there are lint errors — that's expected
    // and the JSON is still on stdout. A missing stdout means eslint
    // itself crashed (config error, parser crash, OOM, etc.) — that's a
    // hard failure, not something the ratchet can meaningfully compare.
    if (typeof err.stdout !== 'string' || err.stdout.trim() === '') {
      console.error('eslint failed to produce output (crash, not a lint failure):');
      console.error(err.stderr || err.message);
      exit(1);
    }
    stdout = err.stdout;
  }
  try {
    return JSON.parse(stdout);
  } catch {
    console.error('Could not parse eslint JSON output — eslint likely crashed mid-run.');
    exit(1);
  }
}

function buildCounts(results) {
  /** @type {Record<string, Record<string, number>>} */
  const counts = {};
  for (const file of results) {
    if (!file.messages.length) continue;
    const relPath = relative(root, file.filePath).split('\\').join('/');
    const perRule = {};
    for (const msg of file.messages) {
      if (msg.severity !== 2) continue; // only errors ratchet; warnings are advisory
      const rule = msg.ruleId || '(parse-error)';
      perRule[rule] = (perRule[rule] || 0) + 1;
    }
    if (Object.keys(perRule).length) counts[relPath] = perRule;
  }
  return counts;
}

function totalErrors(counts) {
  let total = 0;
  for (const rules of Object.values(counts)) {
    for (const n of Object.values(rules)) total += n;
  }
  return total;
}

const results = runEslintJson();
const current = buildCounts(results);

if (argv.includes('--update-baseline')) {
  const baseline = {
    _comment:
      'Generated by scripts/check-lint-ratchet.mjs --update-baseline. ' +
      'Do not hand-edit. Regenerate only after actually fixing errors.',
    generatedAt: new Date().toISOString(),
    totalErrors: totalErrors(current),
    totalFiles: Object.keys(current).length,
    files: current,
  };
  writeFileSync(BASELINE_PATH, JSON.stringify(baseline, null, 2) + '\n');
  console.log(
    `Wrote ${BASELINE_PATH}: ${baseline.totalErrors} errors across ${baseline.totalFiles} files.`
  );
  exit(0);
}

if (!existsSync(BASELINE_PATH)) {
  console.error(
    `Missing ${BASELINE_PATH}. Run 'node scripts/check-lint-ratchet.mjs --update-baseline' once to create it.`
  );
  exit(1);
}

const baseline = JSON.parse(readFileSync(BASELINE_PATH, 'utf8'));
const baselineFiles = baseline.files || {};

let failed = false;
const problems = [];

for (const [file, rules] of Object.entries(current)) {
  const baseRules = baselineFiles[file] || {};
  for (const [rule, count] of Object.entries(rules)) {
    const baseCount = baseRules[rule] || 0;
    if (count > baseCount) {
      failed = true;
      problems.push(
        `  ${file}: ${rule} has ${count} error(s), baseline allows ${baseCount}` +
          (baseCount === 0 ? ' (new violation)' : ' (regression)')
      );
    }
  }
}

const currentTotal = totalErrors(current);
if (failed) {
  console.error('Lint ratchet FAILED — new or increased errors vs scripts/lint-baseline.json:\n');
  console.error(problems.join('\n'));
  console.error(
    `\nCurrent total: ${currentTotal} errors. Baseline total: ${baseline.totalErrors} errors.`
  );
  console.error(
    '\nFix the new/increased violations above. If you genuinely fixed pre-existing errors ' +
      'elsewhere in this same change (lowering the total), re-run with --update-baseline and ' +
      'commit the updated scripts/lint-baseline.json.'
  );
  exit(1);
}

console.log(
  `Lint ratchet passed: ${currentTotal} errors (baseline: ${baseline.totalErrors}). ` +
    (currentTotal < baseline.totalErrors
      ? `${baseline.totalErrors - currentTotal} fewer than baseline — consider running --update-baseline to lock in the improvement.`
      : 'No new or increased violations.')
);
exit(0);
