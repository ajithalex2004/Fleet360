#!/usr/bin/env node
/**
 * scripts/check-typecheck-ratchet.mjs
 *
 * CI ratchet for `tsc --noEmit`, same shape as check-no-runtime-ddl.mjs:
 * the codebase has a known set of pre-existing TypeScript errors (see
 * next.config.ts's `typescript.ignoreBuildErrors: true` and CI's
 * `Typecheck (advisory)` step, both marked TODO(KNOWN-TS-001)) that make a
 * flat "tsc must pass" gate impossible to turn on without first fixing all
 * of them in one pass. This script makes the gate real without requiring
 * that: it fails ONLY when a file that did NOT previously have type errors
 * now has one — i.e. it blocks new type errors while the existing debt in
 * scripts/typecheck-baseline.json is paid down incrementally, exactly like
 * KNOWN_VIOLATIONS in check-no-runtime-ddl.mjs.
 *
 * USAGE
 * ─────
 *   node scripts/check-typecheck-ratchet.mjs
 *       Run the gate: fail if any file outside the baseline has a type
 *       error. This is what CI runs.
 *
 *   node scripts/check-typecheck-ratchet.mjs --update-baseline
 *       Regenerate scripts/typecheck-baseline.json from the CURRENT
 *       `tsc --noEmit` output and write it. Run this deliberately, as its
 *       own reviewed change, whenever the baseline should move — never as
 *       a side effect of an unrelated PR. Shrinking the baseline (fixing
 *       existing errors) should always go through this too, so the file
 *       stays an accurate record of what's actually clean.
 *
 * NOTE ON THE COMMITTED BASELINE
 * ───────────────────────────────
 * scripts/typecheck-baseline.json was seeded from tsc-errors.txt at the
 * repo root (a snapshot already present in this repo, not freshly
 * generated by this script) rather than a live `tsc --noEmit` run, because
 * that run did not finish within this environment's time budget. Before
 * relying on this gate, run `node scripts/check-typecheck-ratchet.mjs
 * --update-baseline` once on a machine where a full typecheck completes in
 * reasonable time, review the diff, and commit it — that becomes the real,
 * verified baseline.
 *
 * `.next/**` paths are excluded everywhere: they're Next.js's own
 * generated route-typing output, regenerated on every build, not source
 * you can fix.
 */

import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { resolve, join } from 'node:path';
import { exit, argv } from 'node:process';

const root = resolve(fileURLToPath(new URL('.', import.meta.url)), '..');
const BASELINE_PATH = join(root, 'scripts', 'typecheck-baseline.json');

const ERROR_LINE_RE = /^(.+?)\((\d+,\d+)\): error TS\d+:/;

const TSC_BIN = join(root, 'node_modules', 'typescript', 'bin', 'tsc');

function runTsc() {
  try {
    const out = execFileSync(process.execPath, [TSC_BIN, '--noEmit', '--pretty', 'false'], {
      cwd: root,
      encoding: 'utf8',
      maxBuffer: 64 * 1024 * 1024,
    });
    return out; // no errors → tsc exits 0, nothing to parse
  } catch (err) {
    const combined = `${err.stdout || ''}\n${err.stderr || ''}`.trim();
    if (!combined) {
      console.error('Failed to run tsc or tsc produced no output:', err);
      process.exit(1);
    }
    return combined;
  }
}

function parseErrorFiles(tscOutput) {
  const files = new Set();
  for (const line of tscOutput.split('\n')) {
    const m = ERROR_LINE_RE.exec(line);
    if (!m) continue;
    const rel = m[1].trim().replace(/\\/g, '/');
    if (rel.startsWith('.next/')) continue; // generated, not source
    files.add(rel);
  }
  return files;
}

function loadBaseline() {
  if (!existsSync(BASELINE_PATH)) return new Set();
  const data = JSON.parse(readFileSync(BASELINE_PATH, 'utf8'));
  return new Set(data.files || []);
}

function writeBaseline(files) {
  const sorted = [...files].sort();
  const payload = {
    _comment:
      'Generated by `node scripts/check-typecheck-ratchet.mjs --update-baseline`. ' +
      'Files listed here are allowed to have pre-existing tsc errors; the gate ' +
      'fails only when a file NOT in this list gains one. Do not hand-edit — ' +
      'regenerate via the script so it always reflects a real tsc run.',
    generatedAt: new Date().toISOString(),
    files: sorted,
  };
  writeFileSync(BASELINE_PATH, JSON.stringify(payload, null, 2) + '\n', 'utf8');
  return sorted;
}

function main() {
  const updateMode = argv.includes('--update-baseline');

  console.log('Running `tsc --noEmit`… (this can take a while)');
  const output = runTsc();
  const currentFiles = parseErrorFiles(output);

  if (updateMode) {
    const previous = loadBaseline();
    const added = [...currentFiles].filter(f => !previous.has(f));
    const removed = [...previous].filter(f => !currentFiles.has(f));
    const sorted = writeBaseline(currentFiles);
    console.log(`\nBaseline written: ${sorted.length} file(s) with pre-existing errors.`);
    if (added.length) {
      console.log(`\n  Newly added to baseline (${added.length}):`);
      added.forEach(f => console.log(`    + ${f}`));
    }
    if (removed.length) {
      console.log(`\n  Removed from baseline — these are now clean (${removed.length}):`);
      removed.forEach(f => console.log(`    - ${f}`));
    }
    console.log('\nReview this diff before committing scripts/typecheck-baseline.json.');
    return;
  }

  const baseline = loadBaseline();
  const newFiles = [...currentFiles].filter(f => !baseline.has(f));
  const staleFiles = [...baseline].filter(f => !currentFiles.has(f));

  if (newFiles.length > 0) {
    console.error(`\n✗  typecheck ratchet FAILED — new type error(s) outside the baseline:\n`);
    newFiles.forEach(f => console.error(`   ${f}`));
    console.error(
      `\n  ${newFiles.length} file(s) newly failing; ${baseline.size} pre-existing file(s) are allowed.`
    );
    console.error(
      '  Fix the new error(s), or if this is deliberately accepted debt, run\n' +
        '  `node scripts/check-typecheck-ratchet.mjs --update-baseline` as its own\n' +
        '  reviewed change and explain why in that PR.\n'
    );
    exit(1);
  }

  if (staleFiles.length > 0) {
    console.log(
      `\n  ${staleFiles.length} file(s) in the baseline are now clean — run ` +
        '`node scripts/check-typecheck-ratchet.mjs --update-baseline` to shrink it:'
    );
    staleFiles.forEach(f => console.log(`    - ${f}`));
    console.log('');
  }

  console.log(
    `✓  typecheck ratchet passed — ${currentFiles.size} file(s) with pre-existing errors, ` +
      `${baseline.size} allowed` +
      (staleFiles.length ? ` (${staleFiles.length} could be removed — see above)` : '') +
      '.'
  );
}

main();
